-- Фикс падения ночного импорта ФТК: атрибут "Подробнее о товаре" длиннее 255 символов
-- ронял INSERT (varchar(255) too long), после чего PostgreSQL помечал транзакцию чанка
-- aborted (25P02) и все последующие товары чанка каскадно падали следом.

-- а) attribute_value больше не ограничен 255 символами
ALTER TABLE product_attributes ALTER COLUMN attribute_value TYPE TEXT;

-- б) Индекс пересоздаём как частичный: служебные атрибуты (ProductAttributeExclusions)
-- в фасетах/карточке не участвуют, поэтому в индексе не нужны. Это также страхует
-- от лимита b-tree ~2704 байта на запись индекса, который TEXT-значения могли бы превысить.
--
-- ВНИМАНИЕ: список ниже ПРОДУБЛИРОВАН из
-- product-service/src/main/java/ru/rfsnab/productservice/service/ProductAttributeExclusions.java (NAMES).
-- При изменении списка в Java-классе ОБЯЗАТЕЛЬНО обновить и этот SQL, иначе индекс
-- перестанет соответствовать реальному отсеву (либо не будет применяться оптимизатором,
-- либо начнёт включать длинные значения служебных атрибутов).
DROP INDEX IF EXISTS idx_product_attributes_name_value;

CREATE INDEX IF NOT EXISTS idx_product_attributes_name_value
    ON product_attributes (attribute_name, attribute_value)
    WHERE attribute_name NOT IN (
        'Признак акция',
        'Признак наличия',
        'Срок доставки заказного товара',
        'Количество в поставке',
        'Признак нестандартного размера',
        'Аналоги',
        'Видео',
        'Сертификаты',
        'Заключение МинПромТорг',
        'ТР ТС',
        'Сопутствующие',
        'Материалы к товару',
        'Популярность (для сортировки)',
        'Новинка (для сортировки)',
        'Дата ближайшей поставки',
        'Другие цвета',
        'Вес (кг. за 1 шт.)',
        'Кратность',
        'Подробнее о товаре',
        'Тип товара'
    );

-- в) Описание товара для покупателя из импорта (ФТК "Подробнее о товаре"), независимо
-- от ручного Product.description, редактируемого в админке — description импортом не затирается.
ALTER TABLE products ADD COLUMN import_description TEXT;
